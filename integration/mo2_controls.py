"""Journaled normalization of the one header comment MO2 moves on startup."""
import hashlib
import json
from pathlib import Path
import shutil
import uuid

import materialize as mat

COMMENT = b'# This file was automatically generated by Mod Organizer.'
PROFILES = {'Unified Skyrim', 'Unified Build', 'FC Diagnostic', 'FC Diagnostic 2'}


def canonical_modlist(blob):
    bom = b'\xef\xbb\xbf' if blob.startswith(b'\xef\xbb\xbf') else b''
    lines = blob[len(bom):].splitlines(keepends=True)
    matches = [i for i, line in enumerate(lines) if line.rstrip(b'\r\n') == COMMENT]
    if len(matches) > 1:
        raise ValueError('Duplicate MO2-generated comments')
    if not matches or matches[0] == 0:
        return blob
    index = matches[0]
    line = lines.pop(index)
    if not line.endswith((b'\r', b'\n')):
        ending = next((b'\r\n' if row.endswith(b'\r\n') else b'\n' for row in lines if row.endswith(b'\n')), b'\r\n')
        line += ending
    return bom + line + b''.join(lines)


def pin(path):
    path = Path(path).resolve(strict=True)
    return {'path': str(path), 'sha256': mat.sha(path), 'size_bytes': path.stat().st_size}


def normalize_profile(profile, receipt_directory=None):
    profile = Path(profile).resolve(strict=True)
    if profile.parent != (mat.TARGET / 'profiles').resolve() or profile.name not in PROFILES:
        raise ValueError('Only prepared integration profiles may be normalized')
    target = mat.guard_destination(profile / 'modlist.txt')
    original = target.read_bytes()
    canonical = canonical_modlist(original)
    result = {'profile': str(profile), 'control': str(target), 'changed': canonical != original,
              'before_sha256': mat.sha(target), 'after_sha256': hashlib.sha256(canonical).hexdigest(),
              'code': pin(__file__), 'scope': 'Move only the exact MO2-generated comment to the first row; no mod/order changes'}
    if canonical == original:
        return result
    if receipt_directory is None:
        raise ValueError('A fresh receipt directory is required before modifying a profile control')
    folder = Path(receipt_directory).resolve()
    mat.within(folder, mat.BASE / 'integration/research')
    if folder.exists():
        raise FileExistsError('Use a fresh normalization receipt directory')
    folder.mkdir(parents=True)
    stat = target.stat()
    if stat.st_nlink != 1 or not target.is_file():
        raise ValueError('Profile control must be a private plain file')
    if shutil.disk_usage(mat.BASE).free < mat.RESERVE + len(original) + len(canonical) + 8192:
        raise RuntimeError('Disk reserve would be crossed')
    before = folder / 'before.txt'
    after = folder / 'after.txt'
    before.write_bytes(original)
    after.write_bytes(canonical)
    result.update(before=pin(before), after=pin(after))
    c = mat.connect()
    unit = 'mo2_control_' + uuid.uuid4().hex
    old = None
    try:
        relative = target.relative_to(mat.TARGET).as_posix()
        old = c.execute('select * from files where dest_key=?', (mat.key(relative),)).fetchone()
        if not old or old['status'] != 'materialized' or old['storage'] != 'private' or old['sha256'] != result['before_sha256']:
            raise ValueError('Journal does not pin the current private profile control')
        old = dict(old)
        mapping = [{'source': str(after), 'destination': relative, 'storage': 'private', 'bytes': len(canonical)}]
        c.execute('begin immediate')
        c.execute('delete from files where id=?', (old['id'],))
        c.execute('insert into events values(?,?,?)', (mat.utc(), 'mo2_control_prior_row', json.dumps({'unit': unit, 'row': old})))
        mat.add_file_mapping(c, unit, mapping, 'Exact MO2-generated comment relocation only')
        if mat.sha(target) != result['before_sha256']:
            raise RuntimeError('Profile control changed before normalization')
        digest = mat.make_private(after, target, after.stat())
        if digest != result['after_sha256']:
            raise RuntimeError('Normalized control SHA mismatch')
        c.execute("update files set status='materialized',sha256=? where unit_id=? and dest_key=?",
                  (digest, unit, mat.key(relative)))
        c.execute('insert into events values(?,?,?)', (mat.utc(), 'mo2_control_normalized', json.dumps(result)))
        c.commit()
    except BaseException:
        if old is not None:
            mat.make_private(before, target, before.stat())
            c.execute('delete from files where unit_id=?', (unit,))
            c.execute('delete from units where id=?', (unit,))
            columns = ','.join(old)
            c.execute(f'insert into files({columns}) values({",".join("?" for _ in old)})', tuple(old.values()))
            c.commit()
        raise
    finally:
        c.close()
    if mat.sha(target) != result['after_sha256']:
        raise RuntimeError('Normalized profile control changed unexpectedly')
    result['status'] = 'NORMALIZED_ONLY_GENERATED_COMMENT_POSITION'
    (folder / 'result.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return result


def reconcile_modlist(expected, actual, allowed_disabled_mods=()):
    if actual == expected:
        return {'status': 'EXACT_BYTES', 'added_disabled_mods': []}
    if actual == canonical_modlist(expected):
        return {'status': 'GENERATED_COMMENT_POSITION_ONLY', 'added_disabled_mods': []}
    bom = b'\xef\xbb\xbf' if expected.startswith(b'\xef\xbb\xbf') else b''
    lines = expected[len(bom):].splitlines(keepends=True)
    if not lines or lines[0].rstrip(b'\r\n') != COMMENT:
        raise ValueError('Only a canonical prepared modlist can be reconciled')
    if any(not mod or mod != Path(mod).name or mod.startswith(('-', '+', '*')) for mod in allowed_disabled_mods):
        raise ValueError('Invalid disabled-mod allowance')
    ending = b'\r\n' if lines[0].endswith(b'\r\n') else b'\n'
    additions = [b'-' + mod.encode('utf-8') + ending for mod in allowed_disabled_mods]
    permitted = bom + lines[0] + b''.join(additions) + b''.join(lines[1:])
    if actual != permitted:
        raise ValueError('Modlist is not exact, apart from the approved disabled additions in their specified order')
    return {'status': 'APPROVED_MO2_DISABLED_ADDITIONS_ONLY', 'added_disabled_mods': list(allowed_disabled_mods)}


def audit_profile_controls(profile, expected, expected_modlist_path, allowed_disabled_mods=()):
    profile = Path(profile).resolve(strict=True)
    if profile.parent != (mat.TARGET / 'profiles').resolve() or profile.name not in PROFILES:
        raise ValueError('Only prepared integration profile controls may be audited')
    changed = []
    reconciled = {}
    for name, digest in expected.items():
        path = profile / name
        actual = mat.sha(path)
        if actual == digest:
            continue
        if name != 'modlist.txt':
            changed.append(name)
            continue
        snapshot = Path(expected_modlist_path).resolve(strict=True)
        try:
            expected_modlist = snapshot.read_bytes()
            if hashlib.sha256(expected_modlist).hexdigest() != digest:
                raise ValueError('Prepared modlist snapshot does not match its pinned digest')
            receipt = reconcile_modlist(expected_modlist, path.read_bytes(), allowed_disabled_mods)
        except (OSError, ValueError) as exc:
            changed.append(name)
            reconciled[name] = {'status': 'REJECTED', 'error': str(exc), 'actual_sha256': actual}
        else:
            reconciled[name] = {**receipt, 'actual_sha256': actual}
    return {'changed_controls': changed, 'reconciled_controls': reconciled}
